def search_laws(text: str, top: int = 5) -> list[dict]:
    """按关键词包含匹配检索法规条目。

    返回 [{law, article, text, hit_keys}]；无命中返回 []（三源脚注 miss）。
    """
    if not text or not text.strip():
        return []
    hit_keys: set[str] = set()
    hit_words: set[str] = set()  # 已命中分类的全体关键词（hay 匹配用）
    for key, words in _TAXONOMY:
        if any(w in text for w in words):
            hit_keys.add(key)
            hit_words.update(words)
    results: list[dict] = []
    for item in _LAWS:
        hay = f"{item['law']} {item['article']} {item['text']}"
        if any(w in hay for w in hit_words) or any(w in text for w in (item["article"], item["law"].split("（")[0])):
            results.append(item)
    return results[:top]


def law_brief() -> int:
    return len(_LAWS)