def seed_demo() -> dict:
    init_db()
    settings = get_settings()
    db = SessionLocal()
    try:
        # ① 全量同步（产品引擎 + 夹具客户端）
        result = asyncio.run(
            SyncEngine(settings, client=FakeBitableClient(CASES, SONGS), db=db).run_full()
        )
        # ② 清洗管道全量重跑
        clean = clean_job()
        # ③ 指标重算快照
        metrics = metrics_job()
        cases = db.scalar(select(func.count()).select_from(Case)) or 0
        raw = db.scalar(select(func.count()).select_from(RawCase)) or 0
        dirty = (
            db.execute(
                select(func.count()).select_from(Case).where(Case.dirty_flags.is_not(None))
            ).scalar()
            or 0
        )
        return {
            "sync": result,
            "clean": clean,
            "metrics": metrics,
            "counts": {"cases": cases, "raw_cases": raw, "dirty_cases": dirty},
        }
    finally:
        db.close()


if __name__ == "__main__":
    import json

    out = seed_demo()
    print(json.dumps(out, ensure_ascii=False, indent=2, default=str))